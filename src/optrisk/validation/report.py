def _tolerance_table() -> str:
    rows = [
        ("Analytic price vs QuantLib", T.QL_BSM_PRICE.describe()),
        ("Analytic Greeks vs QuantLib", T.QL_BSM_GREEK.describe()),
        ("Put-call parity", T.PARITY.describe()),
        ("Price bounds slack", f"{T.BOUNDS_SLACK:g}"),
        ("Greeks vs finite differences", T.FD_GREEK.describe()),
        ("IV price round trip", T.IV_PRICE_ROUNDTRIP.describe()),
        ("IV volatility recovery (vega >= %g)" % T.IV_MIN_VEGA, T.IV_VOL_RECOVERY.describe()),
        ("Tree price (n=%d)" % T.TREE_STEPS, f"{T.TREE_PRICE_SCALE} * S*sigma*sqrt(T)/n + {T.TREE_PRICE_RTOL:g}*|ref|"),
        ("Tree Greeks (n=%d), fraction of natural scale" % T.TREE_GREEK_STEPS, str(T.TREE_GREEK_SCALED)),
        ("Monte Carlo vs reference", f"|diff| <= {T.MC_Z:g} standard errors"),
        ("MC pooled 95% coverage", str(T.MC_COVERAGE_POOLED)),
        ("MC SE / empirical std", str(T.MC_SE_RATIO)),
        ("Antithetic variance ratio", f">= {T.MC_VR_MIN_RATIO}"),
        ("American vs QuantLib FD", T.AMERICAN_VS_QL_FD.describe()),
    ]
    return md_table(["Check", "Tolerance"], rows, align_right_from=9)


def render_markdown(
    results: list[CheckResult],
    grid: Grid,
    quick: bool,
    title: str = "Validation report",
    intro: str = "Generated by `optrisk validate`.",
) -> str:
    env = environment()
    spec = QUICK if quick else FULL
    n_pass = sum(r.status == "passed" for r in results)
    n_fail = sum(r.status == "failed" for r in results)
    n_skip = sum(r.status == "skipped" for r in results)
    lines = [
        f"# {title}",
        "",
        f"**Result: {n_pass} passed, {n_fail} failed, {n_skip} skipped** ({'quick' if quick else 'full'} grid)",
        "",
        f"{intro} Tolerances are defined in `src/optrisk/validation/tolerances.py` and were fixed before these results were generated.",
        "",
        "## Environment",
        "",
        environment_table(env),
        "",
        "## Validation grid",
        "",
        f"{len(grid):,} contracts (calls and puts), spot = 100. Every combination of:",
        "",
        md_table(
            ["Dimension", "Values"],
            [
                ("Strike / spot", ", ".join(map(str, spec["moneyness"]))),
                ("Days to expiry (ACT/365)", ", ".join(map(str, spec["days"]))),
                ("Volatility", ", ".join(map(str, spec["vol"]))),
                ("Risk-free rate", ", ".join(map(str, spec["rate"]))),
                ("Dividend yield", ", ".join(map(str, spec["div"]))),
            ],
            align_right_from=9,
        ),
        "",
        "## Tolerances",
        "",
        "A value passes when `|value - reference| <= atol + rtol * |reference|`. The absolute term matters when the reference is near zero (deep out-of-the-money, short-dated), where a relative test alone would fail on harmless rounding.",
        "",
        _tolerance_table(),
        "",
        "## Summary",
        "",
        md_table(
            ["Check", "Status", "Cases", "Failed", "Max abs error", "Max error / allowed", "Worst case"],
            [
                [r.title, r.status, r.n_cases, r.n_failed, r.max_abs_error, r.max_utilisation, r.worst_case]
                for r in results
            ],
            digits=3,
            align_right_from=2,
        ),
        "",
        "`Max error / allowed` is the largest ratio of observed error to permitted error over all cases; a value below 1 means every case passed, and the number shows the margin. For the variance-reduction row it shows the smallest variance ratio instead.",
        "",
        "## Details",
        "",
    ]
    for r in results:
        lines += [f"### {r.title}", "", f"*{r.what}*" if r.what else "", "", f"- Status: **{r.status}**", f"- Tolerance: {r.tolerance}"]
        if r.notes:
            lines.append(f"- Notes: {r.notes}")
        lines.append("")
        for name, rows in r.tables.items():
            lines += [f"**{name.replace('_', ' ')}**", "", dict_table(rows, digits=4), ""]
    return "\n".join(lines).rstrip() + "\n"


def run_validation(outdir: str | Path, quick: bool = False, progress: Callable[[str], None] | None = None) -> tuple[list[CheckResult], Path]:
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    results, grid = run_all(quick=quick, progress=progress)
    md = out / "validation_report.md"
    md.write_text(render_markdown(results, grid, quick), encoding="utf-8")
    write_json(
        out / "validation_results.json",
        {
            "environment": environment(),
            "grid_size": len(grid),
            "quick": quick,
            "results": [
                {
                    "name": r.name,
                    "title": r.title,
                    "status": r.status,
                    "tolerance": r.tolerance,
                    "n_cases": r.n_cases,
                    "n_failed": r.n_failed,
                    "max_abs_error": r.max_abs_error,
                    "max_utilisation": r.max_utilisation,
                    "worst_case": r.worst_case,
                    "notes": r.notes,
                }
                for r in results
            ],
        },
    )
    return results, md


QUANTLIB_CHECKS = ("quantlib_bsm", "quantlib_tree", "quantlib_mc", "american_quantlib")

_QL_INTRO = (
    "Generated by `optrisk quantlib-compare`. QuantLib is used only as an independent reference; none of its pricing code is used by optrisk. "
    "Conventions are matched explicitly: Actual365Fixed day counter, NullCalendar (no holidays), flat continuously compounded risk-free and dividend curves, "
    "constant Black volatility, valuation date set as the QuantLib evaluation date. QuantLib vega (per 1.0 vol), rho (per 1.0 rate) and theta (per year) are converted "
    "to optrisk units (per vol point, per rate point, per calendar day = theta/365) in `validation/quantlib_ref.py` and nowhere else."
)


def run_quantlib_comparison(outdir: str | Path, quick: bool = False, progress: Callable[[str], None] | None = None) -> tuple[list[CheckResult], Path]:
    """Only the QuantLib-referenced checks, written to ``quantlib_comparison.md``."""
    from . import checks as C
    from .grid import validation_grid
    from .quantlib_ref import quantlib_available

    if not quantlib_available():
        raise RuntimeError("QuantLib is not installed. Install it with `pip install QuantLib` (or `pip install -e .[reference]`).")
    say = progress or (lambda s: None)
    grid = validation_grid(quick=quick)
    results: list[CheckResult] = []
    say("  analytic engine vs QuantLib ...")
    results.append(C.check_quantlib_bsm(grid))
    say("  CRR tree vs QuantLib ...")
    results.append(C.check_quantlib_tree(grid))
    say("  Monte Carlo vs QuantLib ...")
    results.append(C.check_quantlib_mc(grid))
    say("  American exercise vs QuantLib ...")
    results.extend(r for r in C.check_american() if r.name in QUANTLIB_CHECKS)
    out = Path(outdir)
    out.mkdir(parents=True, exist_ok=True)
    md = out / "quantlib_comparison.md"
    md.write_text(render_markdown(results, grid, quick, "QuantLib comparison", _QL_INTRO), encoding="utf-8")
    return results, md
